  <h3>Clientes</h3>

  <p><b>Objetivo:</b> cadastrar e manter os dados do cliente para facilitar pedidos e entregas.</p>

  <p><b>Como acessar:</b> Menu Cadastro → Clientes</p>

  <h4>Como cadastrar um cliente</h4>
  <ol>
    <li>Clique em <b>Novo</b></li>
    <li>Informe <b>Nome</b> e <b>Telefone</b></li>
    <li>(Opcional) Informe <b>CPF/CNPJ</b></li>
    <li>Clique em <b>Salvar</b></li>
  </ol>

  <h4>Boas práticas</h4>
  <ul>
    <li>Cadastre sempre o telefone corretamente (facilita entregas e cobranças).</li>
    <li>Use observações para referência de entrega (ex: “casa do fundo”).</li>
  </ul>

  <h4>Problemas comuns</h4>
  <ul>
    <li><b>Não salva:</b> verifique campos obrigatórios.</li>
    <li><b>Cliente duplicado:</b> pesquise por telefone antes de cadastrar.</li>
  </ul>
</div>