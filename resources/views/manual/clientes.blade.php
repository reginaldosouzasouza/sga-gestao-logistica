<h3>Cadastro de Clientes</h3>

<p><strong>Objetivo:</strong> registrar e manter os dados dos clientes para controle de pedidos, entregas e financeiro.</p>

<h4>Como acessar</h4>

<p><strong>Menu Cadastro → Clientes</strong></p>

<h4>Campos do Cadastro</h4>

<ul>
<li><strong>Nome:</strong> Nome completo do cliente (obrigatório).</li>
<li><strong>Telefone:</strong> Número principal para contato (obrigatório).</li>
<li><strong>CPF:</strong> Documento do cliente (obrigatório).</li>
<li><strong>Email:</strong> E-mail para contato (opcional).</li>
<li><strong>Data de Nascimento:</strong> Informação opcional.</li>
<li><strong>Endereço:</strong> Rua ou logradouro(obrigatório).</li>
<li><strong>Número:</strong> Número do imóvel(obrigatório).</li>
<li><strong>Bairro:</strong> Bairro do cliente(obrigatório).</li>
<li><strong>Cidade:</strong> Cidade do cliente(obrigatório).</li>
<li><strong>Observação:</strong> Informações adicionais (ex: referência de entrega).</li>
</ul>

<h4>Como cadastrar um novo cliente</h4>

<ol>
<li>Acesse <strong>Cadastro → Clientes</strong></li>
<li>Clique em <strong>Novo</strong></li>
<li>Preencha os campos todos os campos (principalmente os capos obrigatórios).</li>
<li>Complete os demais dados se necessário</li>
<li>Clique em <strong>Salvar</strong></li>
</ol>

<h4>Boas Práticas</h4>

<ul>
<li>Evite cadastrar clientes duplicados (pesquise pelo telefone antes).</li>
<li>Preencha corretamente endereço e número para facilitar entregas.</li>
<li>Confirmar endereço completo para evitar erros na entrega.</li>
<li>Utilize o campo Observação para pontos de referência.</li>
</ul>

<h4>Problemas Comuns</h4>

<ul>
<li><strong>Não salva:</strong> verifique se os campos obrigatórios foram  preenchidos.</li>
<li><strong>Cliente duplicado:</strong> utilize a busca antes de cadastrar.</li>
<li><strong>Erro de telefone:</strong> confirme se o número foi digitado corretamente.</li>
</ul>

