<h3>Relatórios</h3>

<p><strong>Objetivo:</strong> fornecer informações estratégicas para análise de desempenho e tomada de decisão.</p>

<p>
O módulo de Relatórios consolida informações dos seguintes setores:
</p>

<ul>
<li>Estoque</li>
<li>Vendas</li>
<li>Compras</li>
<li>Contas a Pagar</li>
<li>Caixa</li>
<li>Gerencial</li>
</ul>

<hr>

<h4>1. Relatório de Estoque</h4>

<p>
Apresenta a quantidade atual de produtos disponíveis.
</p>

<p><strong>Permite:</strong></p>

<ul>
<li>Verificar saldo atual</li>
<li>Identificar produtos com baixo estoque</li>
<li>Acompanhar movimentações</li>
</ul>

<hr>

<h4>2. Relatório de Vendas</h4>

<p>
Exibe todas as vendas realizadas no período selecionado.
</p>

<p><strong>Permite:</strong></p>

<ul>
<li>Analisar faturamento</li>
<li>Identificar produtos mais vendidos</li>
<li>Visualizar vendas por data</li>
<li>Acompanhar desempenho diário ou mensal</li>
</ul>

<hr>

<h4>3. Relatório de Compras</h4>

<p>
Mostra todas as compras registradas no sistema.
</p>

<p><strong>Permite:</strong></p>

<ul>
<li>Controlar entrada de mercadorias</li>
<li>Conferir valores pagos a fornecedores</li>
<li>Auditar movimentações de estoque</li>
</ul>

<hr>

<h4>4. Relatório de Contas a Pagar</h4>

<p>
Lista despesas em aberto e já pagas.
</p>

<ul>
<li>Controle de vencimentos</li>
<li>Planejamento financeiro</li>
<li>Evitar atrasos</li>
</ul>

<hr>

<h4>5. Relatório de Caixa</h4>

<p>
Apresenta todas as entradas e saídas financeiras registradas.
</p>

<ul>
<li>Conferência diária</li>
<li>Auditoria de movimentações</li>
<li>Controle de fluxo de caixa</li>
</ul>

<hr>

<h4>6. Relatório Gerencial</h4>

<p>
Relatório consolidado com visão geral da empresa.
</p>

<ul>
<li>Resumo de faturamento</li>
<li>Resumo de despesas</li>
<li>Resultado financeiro</li>
<li>Análise de desempenho</li>
</ul>

<hr>

<h4>Boas Práticas</h4>

<ul>
<li>Conferir relatórios diariamente.</li>
<li>Utilizar filtros por período para análises mais precisas.</li>
<li>Comparar resultados mensais.</li>
<li>Utilizar relatório gerencial para decisões estratégicas.</li>
</ul>

<hr>

<h4>Importante</h4>

<p>
Os relatórios refletem exatamente as informações registradas nos módulos de:
</p>

<ul>
<li>Movimentação</li>
<li>Financeiro</li>
<li>Compras</li>
</ul>

<p>
Erros nos relatórios geralmente estão relacionados a registros incorretos nos módulos operacionais.
</p>

<p>
Relatórios são ferramentas de análise e não substituem o controle operacional.
</p>

