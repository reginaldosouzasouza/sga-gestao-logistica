<h3>Bem-vindo ao S.G.A – Sistema de Gestão Aplicada</h3>

<p>
O S.G.A é um sistema completo de gestão empresarial desenvolvido para atender
diversos nichos de mercado. Atualmente está configurado para sua operação 
 mas sua estrutura permite adaptação para qualquer segmento.
</p>

<h4>Objetivo do Sistema</h4>

<p>
Controlar de forma organizada todas as operações da empresa, incluindo:
</p>

<ul>
<li>Cadastro de clientes</li>
<li>Controle de pedidos</li>
<li>Gestão de estoque</li>
<li>Contas a pagar</li>
<li>Contas a receber</li>
<li>Controle de caixa</li>
<li>Relatórios gerenciais</li>
</ul>

<h4>Para quem é o S.G.A?</h4>

<ul>
<li><strong>Administrador:</strong> controle total do sistema.</li>
<li><strong>Atendente:</strong> cadastro de clientes e pedidos.</li>
<li><strong>Financeiro:</strong> controle de caixa e contas.</li>
<li><strong>Gestor:</strong> análise de relatórios.</li>
</ul>

<h4>Estrutura do Menu Principal</h4>

<p>O sistema é dividido em quatro áreas principais:</p>

<ul>
<li><strong>Cadastro</strong> – Clientes, Produtos, Fornecedores, Veículos e Usuários.</li>
<li><strong>Movimentação</strong> – Pedidos de Coletas e Consultas de Coleta.</li>
<li><strong>Financeiro</strong> – Contas a pagar, contas a receber.</li>
<li><strong>Relatórios</strong> – Informações estratégicas para tomada de decisão.</li>
</ul>

<p>
Cada módulo possui instruções detalhadas neste manual.
</p>

<h4>Fluxo Básico de Funcionamento</h4>

<p>
O funcionamento do sistema segue a seguinte ordem:
</p>

<ol>
<li>Cadastrar clientes e produtos</li>
<li>Registrar compras (entrada no estoque)</li>
<li>Realizar pedidos (vendas)</li>
<li>Controlar financeiro e caixa</li>
<li>Analisar relatórios</li>
</ol>

<p>
A qualidade das informações depende do correto registro das operações.
</p>

