<h3>Perguntas Frequentes (FAQ)</h3>

<p>
Esta seção responde às dúvidas mais comuns sobre o uso do S.G.A.
</p>

<hr>

<h4>1. Não consigo salvar um cliente. O que fazer?</h4>
<p>
Verifique se os campos obrigatórios (Nome e Telefone) foram preenchidos.
</p>

<hr>

<h4>2. O pedido não aparece no financeiro. Por quê?</h4>
<p>
Verifique a forma de pagamento selecionada:
</p>
<ul>
<li>À vista → entra no Caixa automaticamente.</li>
<li>A prazo → gera Conta a Receber.</li>
</ul>

<hr>

<h4>3. O estoque ficou negativo. O que significa?</h4>
<p>
Significa que houve venda registrada sem que o produto tivesse entrada suficiente no estoque.
Registre corretamente as compras antes de realizar vendas.
</p>

<hr>

<h4>4. Como corrigir um pedido salvo errado?</h4>
<p>
Evite alterar pedidos antigos. O ideal é:
</p>
<ul>
<li>Cancelar o pedido incorreto</li>
<li>Registrar um novo pedido corretamente</li>
</ul>

<hr>

<h4>5. O valor do caixa não confere. O que pode ter acontecido?</h4>
<p>
Possíveis causas:
</p>
<ul>
<li>Recebimento não registrado</li>
<li>Pagamento de conta não lançado</li>
<li>Erro na forma de pagamento do pedido</li>
</ul>

<hr>

<h4>6. Como cadastrar um novo usuário?</h4>
<p>
Acesse:
<strong>Cadastro → Usuários</strong>
</p>
<p>
Recomenda-se criar usuários individuais para cada funcionário.
</p>

<hr>

<h4>7. Posso usar o S.G.A para outro tipo de empresa?</h4>
<p>
Sim. O S.G.A é um Sistema de Gestão Aplicada, podendo ser adaptado para diferentes nichos,
como comércio, serviços e distribuição.
</p>

<hr>

<h4>8. O sistema gera relatórios automaticamente?</h4>
<p>
Sim. Todos os relatórios são baseados nas informações registradas nos módulos operacionais.
Se houver erro nos relatórios, verifique os lançamentos realizados.
</p>

<hr>

<h4>9. O que fazer antes de iniciar o expediente?</h4>
<ul>
<li>Abrir o Caixa</li>
<li>Conferir estoque</li>
<li>Verificar contas vencidas</li>
</ul>

<hr>

<h4>10. O que fazer ao final do expediente?</h4>
<ul>
<li>Conferir relatório de vendas</li>
<li>Conferir relatório de caixa</li>
<li>Verificar contas a receber do dia</li>

<h4>11. Posso vender sem ter estoque disponível?</h4>
<p>
Não é recomendado. O sistema pode permitir o registro, mas isso causará estoque negativo.
</p>

<hr>

<h4>12. Como saber se um cliente está devendo?</h4>
<p>
Acesse o módulo Contas a Receber e filtre pelo nome do cliente.
</p>3
</ul>

