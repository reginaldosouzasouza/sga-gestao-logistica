<h3>Acesso ao Sistema e Perfis de Usuário</h3>

<p><strong>Objetivo:</strong> controlar quem pode acessar o sistema e definir níveis de responsabilidade.</p>

<h4>Tela de Login</h4>

<p>
O acesso ao S.G.A é realizado através da tela de login.
</p>

<p><strong>Campos disponíveis:</strong></p>

<ul>
<li><strong>Cód. Usuário:</strong> código interno do usuário.</li>
<li><strong>Usuário:</strong> nome de login cadastrado.</li>
<li><strong>Senha:</strong> senha de acesso.</li>
</ul>

<p>
Após preencher as informações corretamente, clique em <strong>Entrar</strong>.
</p>

<h4>Usuário MASTER</h4>

<p>
O sistema possui um usuário principal chamado <strong>MASTER</strong>.
</p>

<p>
Este usuário possui acesso total a todos os módulos do sistema:
</p>

<ul>
<li>Cadastros</li>
<li>Movimentação</li>
<li>Financeiro</li>
<li>Relatórios</li>
<li>Configurações</li>
</ul>

<p>
Recomenda-se que o usuário MASTER seja utilizado apenas pelo administrador da empresa.
</p>

<h4>Cadastro de Novos Usuários</h4>

<p>
Novos usuários podem ser cadastrados no menu:
</p>

<p><strong>Cadastro → Usuários</strong></p>

<p>
Ao cadastrar novos usuários, é possível futuramente definir níveis de permissão conforme a necessidade da empresa.
</p>

<h4>Boas Práticas de Segurança</h4>

<ul>
<li>Não compartilhar a senha do usuário MASTER.</li>
<li>Criar usuários individuais para cada funcionário.</li>
<li>Alterar senhas periodicamente.</li>
<li>Revogar acesso de funcionários desligados.</li>
</ul>

<h4>Problemas Comuns</h4>

<ul>
<li><strong>Usuário ou senha incorretos:</strong> verificar digitação.</li>
<li><strong>Não consegue acessar:</strong> verificar se o usuário está ativo.</li>
</ul>

