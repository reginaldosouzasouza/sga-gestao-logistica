<h3>Módulo Financeiro</h3>

<p><strong>Objetivo:</strong> controlar todas as entradas e saídas financeiras da empresa, garantindo organização do fluxo de caixa.</p>

<p>
O módulo financeiro do S.G.A está diretamente integrado ao sistema de Movimentação (Pedidos).
</p>

<ul>
<li>Pedidos à vista → registram entrada no Caixa</li>
<li>Pedidos a prazo → geram Contas a Receber</li>
<li>Compras a prazo → geram Contas a Pagar</li>
<li>Compras a vista  → registram entrada no Caixa</li>
</ul>

<hr>

<h4>1. Contas a Receber</h4>

<p>
Controla valores que clientes ainda precisam pagar.
</p>

<p><strong>Origem:</strong> geradas automaticamente quando um pedido é salvo com pagamento a prazo.</p>

<p><strong>Funções principais:</strong></p>

<ul>
<li>Visualizar parcelas em aberto</li>
<li>Registrar pagamento</li>
<li>Controlar vencimentos</li>
<li>Acompanhar inadimplência</li>
</ul>

<hr>

<h4>2. Contas a Pagar</h4>

<p>
Controla despesas da empresa, como compras de fornecedores e outras obrigações.
</p>

<p><strong>Funções principais:</strong></p>

<ul>
<li>Registrar despesas</li>
<li>Definir data de vencimento</li>
<li>Controlar pagamentos realizados</li>
<li>Evitar atrasos financeiros</li>
</ul>

<hr>

<h4>3. Caixa</h4>

<p>
O Caixa registra todas as entradas e saídas financeiras realizadas no dia.
</p>

<p><strong>Entradas:</strong></p>

<ul>
<li>Vendas à vista</li>
<li>Recebimento de contas</li>
</ul>

<p><strong>Saídas:</strong></p>

<ul>
<li>Pagamentos de contas</li>
<li>Despesas operacionais</li>
</ul>

<hr>

<h4>4. Abertura de Caixa</h4>

<p>
Antes de iniciar as operações diárias, é necessário abrir o caixa.
</p>

<p>
Menu: <strong>Financeiro → Abrir o Caixa</strong>
</p>

<p>
Durante a abertura, pode ser informado o valor inicial disponível(somente no 1º CAIXA).
</p>

<p>
Ao final do dia, o sistema permitirá conferência dos valores registrados.
</p>

<hr>

<h4>Processos Automáticos do Sistema</h4>

<ul>
<li>Pedidos à vista → entram automaticamente no caixa</li>
<li>Pedidos a prazo → geram contas a receber</li>
<li>Baixa de contas → atualiza caixa automaticamente</li>
<p>
Atenção: alterações ou exclusões de pedidos impactam diretamente o estoque e o financeiro.
Recomenda-se cuidado ao modificar registros já concluídos.
</p>
</ul>

<hr>

<h4>Boas Práticas</h4>

<ul>
<li>Abrir o caixa sempre no início do expediente.</li>
<li>Conferir valores antes de fechar o dia.</li>
<li>Registrar todas as movimentações no sistema.</li>
<li>Evitar alterar registros financeiros antigos.</li>
</ul>

<hr>

<h4>Problemas Comuns</h4>

<ul>
<li><strong>Valor divergente no caixa:</strong> verificar registros manuais.</li>
<li><strong>Conta não aparece:</strong> conferir se o pedido foi salvo corretamente.</li>
<li><strong>Recebimento não atualizado:</strong> verificar baixa da conta.</li>
</ul>

