        <strong>🚀 Passo a Passo: Do Login ao Trabalho</strong>
    </div>

    <div style="margin-bottom: 20px;">
        <strong>1. Identificação no Login</strong>
        <p>Na tela inicial, preencha os três campos obrigatórios:</p>
        <ul>
            <li><strong>Cód. Usuário:</strong> O número da sua licença (Ex: 1).</li>
            <li><strong>Usuário:</strong> Seu nome de acesso (Ex: MASTER).</li>
            <li><strong>Senha:</strong> Sua chave de segurança pessoal.</li>
        </ul>
    </div>

    <div style="margin-bottom: 20px;">
        <strong>2. Seletor de Módulos</strong>
        <p>Após o login, você verá os módulos liberados para sua empresa:</p>
        <ul>
            <li>Clique no ícone correspondente ao que deseja operar (ex: <strong>Revenda de Gás</strong>).</li>
            <li><em>Obs: Se algum módulo contratado não aparecer, entre em contato com o suporte.</em></li>
        </ul>
    </div>

    <div style="margin-bottom: 10px;">
        <strong>3. Ambiente de Trabalho</strong>
        <p>Uma vez dentro do módulo, utilize a <strong>Barra Superior</strong> para navegar entre Cadastros, Movimentações e Financeiro.</p>
    </div>

    <div style="background: #fff3cd; padding: 10px; border-radius: 4px; font-size: 13px; border: 1px solid #ffeeba;">
        💡 <strong>Dica de Segurança:</strong> Ao terminar o trabalho ou se ausentar do computador, clique no botão vermelho <strong>Sair</strong> no canto superior direito.
    </div>
</div>






































<div id="manual-suporte">
    <div id="regra-clientes">
        <strong>Cadastro de Clientes:</strong> 
        Registro de Clientes e parceiros. Use palavras-chave como "Novo Cliente" ou "Alterar Endereço". 
        Regra: Para cadastrar, o CPF deve ter 11 dígitos. Se for empresa, use o campo CNPJ. 
        É possível consultar por Nome ou Telefone.
    </div>

    <div id="regra-compras">
        <strong>Entrada de Compras:</strong> 
        Toda compra deve ter o cadastro do fornecedor já pronto. 
        Regra de Ouro: Toda compra que NÃO FOR PIX ou DINHEIRO gera uma conta a pagar automaticamente no sistema.
    </div>

    <div id="regra-fornecedor">
        <strong>Cadastro de Fornecedores:</strong> 
        Registro de entrada de mercadorias ou insumos. Palavra-chave: "Cadastro de Fornecedor".
    </div>

    <div id="regra-veiculos">
        <strong>Produtos e Veículos:</strong> 
        Itens do estoque e bens negociáveis. Palavras-chave: Placa, Chassi, Marca/Modelo. 
        Regra: Veículos exigem quilometragem inicial no cadastro.
    </div>
</div>


<div id="regra-pedidos">
    <strong>Pedidos de Coleta (Venda de Gás e Água):</strong> 
    Esta é a tela principal de vendas e o coração do sistema SGA.
    
    <strong>1. Identificação do Cliente:</strong> Comece pesquisando o cliente por nome ou telefone no campo de busca. Se o cliente não existir, use o atalho 'Cadastrar Cliente'.
    
    <strong>2. Controle de Coleta:</strong> Note o campo 'Controle de Coleta' no canto superior direito. Este número é gerado automaticamente de forma sequencial pelo sistema para cada nova venda, facilitando a organização e auditoria.
    
    <strong>3. Itens e Produtos:</strong> Selecione o produto (Gás ou Água), informe a quantidade e o valor. **Atenção:** Clicar no botão azul 'Adicionar Produto' para que mais  item entre na lista de venda.
    
    <strong>4. Total do Item:</strong> Este cmapo é editável se precisar alterar o valor total do Item.
    
    <strong>5. Pagamento e Total:</strong> Verifique o valor em destaque no canto inferior esquerdo. Escolha a forma de pagamento e o prazo.
    
    <strong>6. Salvar:</strong> Clique em 'Salvar Coleta' para finalizar o processo, baixar o estoque e registrar o financeiro.
</div>